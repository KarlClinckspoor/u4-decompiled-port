#!/usr/bin/env python3
"""Generate port/include/title/trename.h: TITLE.EXE's public names with the prefix T_.

    python3 port/tools/gen_title.py

The port links TITLE.EXE (SRC-TITLE/: the introduction, the character creation) and
AVATAR.EXE (SRC/) into one program. The two share many names (Party, txt_X, u4_puts,
Gra_Init, low_init, ...), so every name TITLE.EXE defines is renamed T_<name> by this
header, force-included in its C files and in the port's files compiled for it: the
functions and globals its C defines (from clang's AST), the PUBLIC names of its assembly
modules (which the port replaces in C), and its main (game_main after compat.h).
The prototypes of the assembly routines its C calls without a declaration follow.
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
ROOT = os.path.dirname(PORT)
SRC = os.path.join(ROOT, 'SRC-TITLE')
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import implicit_int as ii   # noqa: E402  (the AST helper)

# routines of the assembly modules that the C calls with no declaration (int16 results)
ASM_PROTOS = [
    'int16_t u_kbhit(void);',
    'int16_t u_kbread(void);',
    'void u_kbflush(void);',
    'int16_t sound_1(void);',
]


def names_from_ast():
    out = set()
    for name in sorted(os.listdir(SRC)):
        if not name.upper().endswith('.C'):
            continue
        tree = ii.ast(os.path.join(SRC, name), os.path.join(PORT, 'include', 'title'))
        cur = {'file': None}

        def upd(loc):
            if not loc:
                return
            if 'spellingLoc' in loc or 'expansionLoc' in loc:
                upd(loc.get('spellingLoc'))
                upd(loc.get('expansionLoc'))
                return
            if 'file' in loc:
                cur['file'] = loc['file']

        for n in tree.get('inner', []):
            loc = n.get('loc', {})
            upd(loc.get('spellingLoc', loc))
            f = cur['file'] or ''
            upd(loc.get('expansionLoc'))
            upd(n.get('range', {}).get('begin', {}))
            upd(n.get('range', {}).get('end', {}))
            if os.path.dirname(os.path.realpath(f)) != os.path.realpath(SRC) or \
                    os.path.basename(f).upper() == 'PORTABLE.H':
                continue
            if n.get('kind') in ('FunctionDecl', 'VarDecl') and n.get('storageClass') != 'static' \
                    and n.get('name'):
                out.add(n['name'])
    return out


def names_from_asm():
    out = set()
    for name in sorted(os.listdir(SRC)):
        if not name.upper().endswith('.ASM'):
            continue
        for l in open(os.path.join(SRC, name), encoding='latin-1').read().replace('\r', '').split('\n'):
            m = re.match(r'^\s*PUBLIC\s+(.*)$', l, re.I)
            if m:
                for p in m.group(1).split(';')[0].split(','):
                    p = p.strip()
                    if p:
                        out.add(p[1:] if p.startswith('_') else p)
    return out


def main():
    names = (names_from_ast() | names_from_asm() | {'game_main'}) - {'main'}
    out = ['/* Generated by port/tools/gen_title.py: do not edit.',
           ' * TITLE.EXE\'s names, renamed T_<name> so that it links with AVATAR.EXE in one',
           ' * program; force-included (after compat.h) in its C and in the port\'s files built',
           ' * for it. */', '#ifndef PORT_TRENAME_H', '#define PORT_TRENAME_H', '']
    for n in sorted(names, key=str.lower):
        out.append('#define %s T_%s' % (n, n))
    out += ['', '#ifndef PORT_TITLE_RUNTIME', '/* the assembly routines its C calls without declaring them */']
    out += ASM_PROTOS
    out += ['#endif', '', '#endif', '']
    p = os.path.join(PORT, 'include', 'title', 'trename.h')
    open(p, 'w').write('\n'.join(out))
    print('%s: %d names' % (p, len(names)))


if __name__ == '__main__':
    main()
