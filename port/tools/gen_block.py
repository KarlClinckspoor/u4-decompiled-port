#!/usr/bin/env python3
"""Generate the port's DOS-layout data blocks: for each game file with a
"#ifdef PORT_BLOCK / #include "block_<file>.h" / #else ... #endif" section,
port/game/block_<file>.c (the section's variables as one packed block) and
port/include/<program>/block_<file>.h (their declarations).

    python3 port/tools/gen_block.py

Some of the game's tables are read past their end, into the next one: MonsterIndex gives
people an index beyond MonsterMaxHP, which DOS reads from MonsterPartner. In DOS the
compiler lays a file's variables out one after the other; a host compiler aligns and
orders them as it likes. So the port compiles such a section as one packed block: each
variable is an assembler symbol at its DOS offset (the address in front of its name,
/*D_xxxx*/), with the same initial values. Arrays without a size get it from the next
variable's address (the last one from its initializer).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
ROOT = os.path.dirname(PORT)
PROGRAMS = (('SRC', 'avatar', 'u4.h', ''), ('SRC-TITLE', 'title', 'title.h', 'T_'))  # T_: port/include/title/trename.h
SIZES = {'char': 1, 'unsigned char': 1, 'signed char': 1, 'int16': 2, 'uint16': 2, 'int32': 4,
         'uint32': 4, 'U16': 2, 'S16': 2}


def top_level_items(init):
    """the number of top-level elements of a brace initializer"""
    body = init.strip()[1:-1]
    depth, n, cur = 0, 0, ''
    for c in body:
        if c in '{(':
            depth += 1
        elif c in '})':
            depth -= 1
        if c == ',' and depth == 0:
            if cur.strip():
                n += 1
            cur = ''
            continue
        cur += c
    if cur.strip():
        n += 1
    return n


def generate(src_dir, prog, header, prefix, name):
    path = os.path.join(ROOT, src_dir, name)
    src = open(path, encoding='latin-1').read().replace('\r\n', '\n')
    m = re.search(r'#ifdef PORT_BLOCK\n#include "(block_\w+\.h)"\n#else\n(.*?)#endif', src, re.S)
    if not m:
        return False
    hname, region = m.group(1), m.group(2)
    region = re.sub(r'/\*(?!D_[0-9A-F]{4}\*/).*?\*/', '', region, flags=re.S)
    defines = re.findall(r'^#define .*$', region, re.M)
    decls = re.findall(r'([A-Za-z_][\w ]*?)\s*/\*D_([0-9A-F]{4})\*/\s*(\w+)\s*((?:\[[^\]]*\])*)\s*=\s*(\{.*?\}|[^;{]+);',
                       region, re.S)
    base = int(decls[0][1], 16)
    fields, inits, sets, checks, externs = [], [], [], [], []
    stem = os.path.splitext(hname)[0]
    for i, (typ, addr, var, dims, init) in enumerate(decls):
        typ = ' '.join(typ.split())
        off = int(addr, 16) - base
        if dims.startswith('[]'):
            if i + 1 < len(decls):
                size = int(decls[i + 1][1], 16) - int(addr, 16)
                inner = 1
                for d in re.findall(r'\[(\d+)\]', dims[2:]):
                    inner *= int(d)
                count = size // (SIZES[typ] * inner)
            else:
                count = top_level_items(init)
            dims = '[%d]' % count + dims[2:]
        fields.append('\t%s %s%s;' % (typ, var, dims))
        inits.append('\t' + '\n\t'.join(l.strip() for l in init.strip().split('\n') if l.strip()) + ',')
        sets.append('AT(%s%s, %d)' % (prefix, var, off))
        checks.append('_Static_assert(offsetof(struct %s, %s) == %d, "%s");' % (stem, var, off, var))
        externs.append('extern %s %s%s;' % (typ, var, re.sub(r'^\[\d+\]', '[]', dims)))  # read past
    out = ['/* Generated by port/tools/gen_block.py from %s/%s: do not edit.' % (src_dir, name),
           ' * The variables of its PORT_BLOCK section as one packed block, in DOS\'s order and at',
           ' * DOS\'s offsets, so that reads past one table find the next as in DOS. */',
           '#include <stddef.h>', '#include "%s"' % header, ''] + defines + ['', '#pragma pack(push, 1)',
           'struct %s {' % stem] + fields + ['};', '#pragma pack(pop)', '',
           '#undef extern', 'struct %s u4_%s = {' % (stem, stem)] + inits + ['};', ''] + checks + [
           '', '#if defined(__APPLE__) || (defined(_WIN32) && !defined(_WIN64))',
           '#define SYM(n) "_" #n', '#else', '#define SYM(n) #n', '#endif',
           '#define AT(n, off) __asm__(".globl " SYM(n) "\\n.set " SYM(n) ", " SYM(u4_%s) " + " #off);' % stem,
           ''] + sets + ['']
    os.makedirs(os.path.join(PORT, 'game'), exist_ok=True)
    open(os.path.join(PORT, 'game', stem + '.c'), 'w').write('\n'.join(out))
    hdr = ['/* Generated by port/tools/gen_block.py from %s/%s: do not edit.' % (src_dir, name),
           ' * The declarations of its PORT_BLOCK section\'s variables (port/game/%s.c). */' % stem] + externs + ['']
    open(os.path.join(PORT, 'include', prog, hname), 'w').write('\n'.join(hdr))
    print('%s: %d variables' % (stem, len(decls)))
    return True


def main():
    for src_dir, prog, header, prefix in PROGRAMS:
        d = os.path.join(ROOT, src_dir)
        for name in sorted(os.listdir(d)):
            if name.upper().endswith('.C'):
                generate(src_dir, prog, header, prefix, name)


if __name__ == '__main__':
    main()
