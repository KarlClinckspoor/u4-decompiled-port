#!/usr/bin/env python3
"""Write port/include/avatar/portprot.h and port/include/title/portprot.h: a prototype of
every function the game's C defines (SRC/ and SRC-TITLE/), for the host build.

    python3 tools/mkprotos.py

The original sources call functions before (or without) declaring them, and declare
most with an empty parameter list: Microsoft C 4.00 passes each argument as a 16-bit
word whatever the callee takes. On a 64-bit host an argument passed without a prototype
is not converted to the parameter's type, and a call through an implicit declaration
takes an int result for any return type; so the port declares every function with its
real parameters before any code (U4.H and TITLE.H include the file at their end, on the
host only). Static functions are declared in a section of their own file, selected by
PORT_TU_<file> (the build defines it). The types come from clang's AST of the sources,
built with the port's headers. Regenerate after changing a definition.
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import implicit_int as ii

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def declarator(name, qualtype, params):
    """'int16 ()' + [(name, type)] -> 'int16 name(int16 a, char *b)' (a K&R definition's
    function type has the promoted types: the parameters' own are taken)"""
    m = re.match(r'^(.*?)\s*\((.*)\)$', qualtype)
    ret = m.group(1).strip()
    out = []
    for i, (n, t) in enumerate(params):
        n = n or 'a%d' % i
        if '(*)' in t:
            out.append(t.replace('(*)', '(*%s)' % n, 1))
        else:
            out.append('%s%s%s' % (t, '' if t.endswith('*') else ' ', n))
    if not params:
        out = ['void']
    return '%s%s%s(%s)' % (ret, '' if ret.endswith('*') else ' ', name, ', '.join(out))


def split_args(s):
    depth, cur, out = 0, '', []
    for c in s:
        if c == ',' and depth == 0:
            out.append(cur)
            cur = ''
            continue
        depth += c == '('
        depth -= c == ')'
        cur += c
    out.append(cur)
    return out


def definitions(tree, src_dir):
    """(name, qualtype, param names, is_static, file) of each function defined in src_dir"""
    cur = {'file': None}
    out = []

    def upd(loc):
        if not loc:
            return
        if 'spellingLoc' in loc or 'expansionLoc' in loc:
            upd(loc.get('spellingLoc'))
            upd(loc.get('expansionLoc'))
            return
        if 'file' in loc:
            cur['file'] = loc['file']

    def walk(n):
        loc = n.get('loc', {})
        upd(loc.get('spellingLoc', loc))
        f = cur['file'] or ''
        upd(loc.get('expansionLoc'))
        upd(n.get('range', {}).get('begin', {}))
        upd(n.get('range', {}).get('end', {}))
        if n.get('kind') == 'FunctionDecl' and any(c.get('kind') == 'CompoundStmt' for c in n.get('inner', [])) \
                and os.path.dirname(os.path.realpath(f)) == os.path.realpath(src_dir):
            params = [(c.get('name'), c['type']['qualType']) for c in n.get('inner', []) if c.get('kind') == 'ParmVarDecl']
            out.append((n['name'], n['type']['qualType'], params, n.get('storageClass') == 'static',
                        os.path.basename(f)))
        for c in n.get('inner', []):
            walk(c)

    walk(tree)
    return out


def main():
    for sub, inc in ii.PROGRAMS:
        d = os.path.join(ROOT, sub)
        incdir = os.path.join(ii.PORT, 'include', inc)
        glob, static = [], {}
        seen = set()
        for name in sorted(os.listdir(d)):
            if not name.upper().endswith('.C'):
                continue
            for fname, qt, params, is_static, f in definitions(ii.ast(os.path.join(d, name), incdir), d):
                if fname == 'main' or (fname, f) in seen:
                    continue
                seen.add((fname, f))
                text = declarator(fname, qt, params) + ';'
                if is_static:
                    static.setdefault(f, []).append(text)
                else:
                    glob.append('%s /* %s */' % (text, f))
        out = ['/* Generated by tools/mkprotos.py: prototypes of the functions %s\'s C defines, for' % sub,
               ' * the host build only (included at the end of its main header under #ifndef M_I86).',
               ' * Do not edit. */', '#ifndef PORTPROT_H', '#define PORTPROT_H', '']
        out += glob
        for f, lines in sorted(static.items()):
            tu = re.sub(r'\W', '_', os.path.splitext(f)[0].upper())
            out += ['', '#ifdef PORT_TU_%s' % tu] + lines + ['#endif']
        out += ['', '#endif', '']
        p = os.path.join(ii.PORT, 'include', inc, 'portprot.h')
        open(p, 'w').write('\n'.join(out))
        print('%s: %d global, %d static prototypes' % (p, len(glob), sum(len(v) for v in static.values())))


if __name__ == '__main__':
    main()
